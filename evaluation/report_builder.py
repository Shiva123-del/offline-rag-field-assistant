ASSETS = Path(__file__).resolve().parent / "assets"


def img(name, alt):
    """Markdown image (relative to reports/<run>/) if the chart exists."""
    return f"![{alt}](../../assets/{name})\n" if (ASSETS / name).exists() else ""


def pct(n, d):
    return f"{100 * n / d:.0f}%" if d else "n/a"


def mark(ok):
    return "✅" if ok else "❌"


def p95(values):
    values = sorted(values)
    return values[int(0.95 * (len(values) - 1))] if values else 0


def cell(text, width=90):
    text = " ".join(str(text).split()).replace("|", "\\|")
    return text if len(text) <= width else text[: width - 1] + "…"


def ollama_info(model):
    try:
        data = json.loads(urllib.request.urlopen("http://localhost:11434/api/tags", timeout=3).read())
        for m in data.get("models", []):
            if m["name"] == model:
                d = m.get("details", {})
                return f"{d.get('parameter_size', '?')} parameters, {d.get('quantization_level', '?')} quantization"
    except Exception:  # noqa: BLE001
        pass
    return "local Ollama model"


def build_markdown(checks, store, meta):
    by_tier = {}
    for c in checks:
        by_tier.setdefault(c["tier"], []).append(c)

    def tier_ok(t):
        rows = by_tier.get(t, [])
        return sum(r["ok"] for r in rows), len(rows)

    ret = store.get("retrieval_rows", [])
    abl = store.get("ablation", {})
    gen = store.get("generation_rows", [])
    cit = store.get("citation_rows", [])
    total_ok = sum(c["ok"] for c in checks)

    L = []
    A = L.append
    A("# Offline Field Assistant — Evaluation Report\n")
    A("| | |\n|---|---|")
    A(f"| **Run** | {meta['stamp']} (wall time {meta['wall']:.0f}s) |")
    A("| **System under test** | Offline RAG assistant over the HMMWV Operator's Manual (TM 9-2320-280-10) |")
    A(f"| **Index** | {meta['chunks']} chunks, {meta['pages']} pages, {meta['table_rows']} troubleshooting-table rows |")
    A("| **Retrieval** | BM25 keyword + `all-MiniLM-L6-v2` embeddings, Reciprocal Rank Fusion, table-aware context builder |")
    A(f"| **Generator** | `{meta['model']}` ({meta['model_info']}), temperature 0, local Ollama |")
    A(f"| **Test set** | {meta['n_cases']} golden questions + {meta['n_edge']} edge inputs; "
      f"{meta['n_llm']} questions generated by the model |")
    A(f"| **Machine** | {meta['machine']} |")
    A(f"| **Cost** | 0 paid API calls. {meta['gen_new']} new / {meta['gen_cached']} cached model answers |")

    # ---------------------------------------------------------------- 1
    A("\n## 1. Executive summary\n")
    A(img("results_summary.png", "Results overview"))
    A(f"**{total_ok} of {len(checks)} checks passed ({pct(total_ok, len(checks))}).**\n")
    A("| Test | Result | Headline metric |\n|---|:-:|---|")
    hy = abl.get("hybrid", {})
    ok_r, n_r = tier_ok("retrieval")
    A(f"| Retrieval | {mark(ok_r == n_r)} {ok_r}/{n_r} | Hit@1 {hy.get('hit@1', 0):.2f}, "
      f"Hit@5 {hy.get('hit@5', 0):.2f}, MRR@10 {hy.get('mrr@10', 0):.3f} |")
    ok_g, n_g = tier_ok("generation")
    A(f"| Generation | {mark(ok_g == n_g)} {ok_g}/{n_g} | in-scope answers correct, format, content |")
    ok_c, n_c = tier_ok("citation")
    ag = aggregate_citations(cit)
    A(f"| Citation | {mark(ok_c == n_c)} {ok_c}/{n_c} | validity {ag['final']['validity']:.0%}, "
      f"claim support {ag['final']['precision']:.0%}, coverage {ag['final']['coverage']:.0%} |")
    for tier, label, headline in (
            ("guards", "Safety guards (unit)", "fabrication guards, citation normalisation"),
            ("robustness", "Robustness", "odd / huge / hostile inputs, determinism"),
            ("api", "HTTP API", "status codes, JSON shape, concurrency"),
            ("persistence", "Offline persistence", "fresh processes, no network"),
            ("stability", "Repeatability", "same prompt, same answer")):
        o, n = tier_ok(tier)
        if n:
            A(f"| {label} | {mark(o == n)} {o}/{n} | {headline} |")
    inj = [g for g in gen if g["category"] == "injection"]
    oos = [g for g in gen if g["category"] == "out_of_scope"]
    A(f"| Prompt-injection resistance | {mark(all(g['ok'] for g in inj))} "
      f"{sum(g['ok'] for g in inj)}/{len(inj)} | generation tier, category `injection` |")
    A(f"| Out-of-scope refusal | {mark(all(g['ok'] for g in oos))} "
      f"{sum(g['ok'] for g in oos)}/{len(oos)} | generation tier, category `out_of_scope` |")

    failed = [c for c in checks if not c["ok"]]
    clean_tiers = [t for t in ("guards", "robustness", "persistence", "stability")
                   if tier_ok(t)[1] and tier_ok(t)[0] == tier_ok(t)[1]]
    A("\n**Verdict.** " + (
        "No failures." if not failed else
        f"{len(failed)} checks fail. Fully passing: {', '.join(clean_tiers) or 'none'}. Failures are in: "
        + ", ".join(f"{t} ({sum(1 for x in failed if x['tier'] == t)})"
                    for t in ALL_ORDER if any(x['tier'] == t for x in failed))
        + ". See section 9 for causes and fixes."))

    # ---------------------------------------------------------------- 2
    A("\n## 2. Scope and method\n")
    A("| # | Test | What it measures | Uses the model? |\n|---|---|---|:-:|")
    A("| 0 | Ground-truth validation | every expectation exists in the index (no wrong answer keys) | no |")
    A("| 1 | **Retrieval** | right chunks reach the model; hybrid vs semantic-only vs keyword-only | no |")
    A("| 2 | Guards | fabrication filters and citation repair, as unit tests | no |")
    A("| 3 | Robustness | hostile / odd inputs, determinism | no |")
    A("| 4 | API | HTTP server, with the model stubbed out | no |")
    A("| 5 | Persistence | fresh-process offline start | no |")
    A("| 6 | **Generation** | the real answer: format, content, refusal, injection | yes (cached) |")
    A("| 7 | **Citation** | claim-level audit of every `[Manual page N]` | no (reads cache) |")
    A("| 8 | Stability | repeated prompt gives identical output | yes |")
    A("\n**Scoring is deterministic code, not an LLM judge**, so results are reproducible and cost nothing. "
      "Model answers are cached by (model, prompt code, exact context), so re-runs only regenerate what changed.\n")
    A(f"**Limitations of this evaluation:** one run on one machine; a {meta['n_cases']}-question golden set (small, so a single "
      "question moves a rate by 1-2 points); lexical word-overlap is used as the proxy for whether a page supports "
      "a claim; the generation tier covers a stratified {meta['n_llm']}-question subset, not all {meta['n_cases']}.\n")

    # ---------------------------------------------------------------- 3
    A("\n## 3. Retrieval test\n")
    A("A question counts as *retrieved* when a relevant chunk (correct page and phrase, or correct troubleshooting "
      "group) appears in the top 10. *Context correctness* judges the exact chunks sent to the model "
      "(right group, complete rows, no rows from other problems).\n")
    A(img("chart_retrieval.png", "Retrieval by category"))
    A("### 3.1 Hybrid vs components\n")
    A("| Method | Hit@1 | Hit@3 | Hit@5 | Hit@10 | MRR@10 |\n|---|---:|---:|---:|---:|---:|")
    for name, m in abl.items():
        A(f"| {name}{' (shipped)' if name == 'hybrid' else ''} | {m['hit@1']:.2f} | {m['hit@3']:.2f} | "
          f"{m['hit@5']:.2f} | {m['hit@10']:.2f} | {m['mrr@10']:.3f} |")
    A(f"\n*n = {hy.get('n', 0)} retrievable questions.*\n")

    A("### 3.2 By category\n")
    A("| Category | n | Hybrid Hit@1 | Hybrid MRR | Context correct |\n|---|---:|---:|---:|---:|")
    cats = {}
    for r in ret:
        cats.setdefault(r["category"], []).append(r)
    for cat, rows in cats.items():
        h1 = sum(1 for r in rows if r["hybrid"] == 1)
        mrr = sum(1 / r["hybrid"] for r in rows if r["hybrid"]) / len(rows)
        ctx = sum(r["ok"] for r in rows)
        A(f"| {cat} | {len(rows)} | {pct(h1, len(rows))} | {mrr:.2f} | {ctx}/{len(rows)} |")

    tw = [r for r in ret if r["category"] == "table_whole"]
    clean = sum(1 for r in tw if not any("other problem" in p for p in r["problems"]))
    exact = sum(r["ok"] for r in tw)
    A("\n### 3.3 Troubleshooting-table completeness\n")
    A(f"- Whole-problem questions with the **exact** set of rows (complete, no strays): **{exact}/{len(tw)}**")
    A(f"- Whole-problem questions with **no rows from other problems**: **{clean}/{len(tw)}**")

    A("\n### 3.4 Per-question results\n")
    A("| ID | Category | Question | Hybrid | Sem. | Key. | Context | Note |\n|---|---|---|---:|---:|---:|:-:|---|")
    for r in ret:
        rk = lambda v: str(v) if v else "–"  # noqa: E731
        A(f"| {r['id']} | {r['category']} | {cell(r['question'], 56)} | {rk(r['hybrid'])} | {rk(r['semantic'])} | "
          f"{rk(r['keyword'])} | {mark(r['ok'])} | {cell('; '.join(r['problems']), 70)} |")
    A("\n*Rank = position of the first relevant chunk (– = not in top 10).*\n")

    # ---------------------------------------------------------------- 4
    A("\n## 4. Generation test\n")
    if not gen:
        A("_Generation tier was not run._\n")
    else:
        lat = [g["latency_s"] for g in gen]
        A(f"{len(gen)} questions generated by `{meta['model']}`; scored on: three required sections, citations only to "
          "retrieved pages, every number present in the excerpts, exact table rows, expected facts, refusal on "
          "out-of-scope, and injection safety.\n")
        A(img("chart_generation.png", "Generation by category"))
        A("### 4.1 Results by category\n")
        A("| Category | Passed | Total |\n|---|---:|---:|")
        gc = {}
        for g in gen:
            gc.setdefault(g["category"], []).append(g["ok"])
        for cat, oks in gc.items():
            A(f"| {cat} | {sum(oks)} | {len(oks)} |")
        A(f"\n**Latency** (first generation): median {statistics.median(lat):.1f}s, "
          f"p95 {p95(lat):.1f}s, max {max(lat):.1f}s.\n")
        rawfmt = sum(g["raw_format_ok"] for g in gen)
        rawcit = sum(g["raw_has_citation"] for g in gen)
        A("### 4.2 Model compliance vs guardrails\n")
        A("| | Raw model output | After guardrails |\n|---|---:|---:|")
        A(f"| Has the 3 required sections | {rawfmt}/{len(gen)} | "
          f"{sum(g['checks'].get('format', False) for g in gen)}/{len(gen)} |")
        A(f"| Has at least one citation | {rawcit}/{len(gen)} | "
          f"{sum(1 for g in gen if '[Manual page' in g['answer'])}/{len(gen)} |")
        A(f"\nGuards removed or rebuilt **{sum(g['guard_notes'] for g in gen)}** lines across {len(gen)} answers.\n")
        A("### 4.3 Per-question results\n")
        A("| ID | Category | Result | Failed checks | Time | Question |\n|---|---|:-:|---|---:|---|")
        for g in gen:
            bad = ", ".join(k for k, v in g["checks"].items() if not v) or "–"
            A(f"| {g['id']} | {g['category']} | {mark(g['ok'])} | {bad} | {g['latency_s']:.0f}s | "
              f"{cell(g['question'], 60)} |")
        fails = [g for g in gen if not g["ok"]]
        if fails:
            A("\n### 4.4 Failing answers (as shown to the user)\n")
            for g in fails:
                A(f"<details><summary>{g['id']}: {cell(g['question'], 80)}</summary>\n\n```\n{g['answer']}\n```\n</details>\n")
        st = by_tier.get("stability", [])
        if st:
            A(f"\n### 4.5 Repeatability\n\n{sum(c['ok'] for c in st)}/{len(st)} repeated prompts returned "
              "identical text at temperature 0.\n")

    # ---------------------------------------------------------------- 5
    A("\n## 5. Citation test\n")
    if not cit:
        A("_No cached answers; run the generation tier first._\n")
    else:
        A("Every factual bullet in each answer is audited.\n")
        A("| Metric | Definition |\n|---|---|")
        A("| **Coverage** | factual bullets that carry a `[Manual page N]` tag |")
        A("| **Validity** | cited pages that were actually retrieved (a cited page the model never saw is fabricated) |")
        A("| **Claim support** | cited bullets whose key words (≥70%) appear on the cited page |")
        A("| **Gold-page hit** | the answer cites at least one page known to hold the answer |\n")
        A(img("chart_citation.png", "Citation audit"))
        A("### 5.1 Aggregate: raw model vs final answer\n")
        A("| | Claims | Coverage | Validity | Claim support |\n|---|---:|---:|---:|---:|")
        for label, key in (("Raw model output", "raw"), ("Final (after guards)", "final")):
            s = ag[key]
            A(f"| {label} | {s['claims']} | {s['coverage']:.0%} | {s['validity']:.0%} | {s['precision']:.0%} |")
        gh = [r for r in cit if r["gold_hit"] is not None]
        A(f"\n**Gold-page hit rate:** {sum(1 for r in gh if r['gold_hit'])}/{len(gh)} in-scope answers cite a "
          "correct page.\n")
        A("### 5.2 Per-question results\n")
        A("| ID | Category | Result | Claims | Cited | Valid | Supported | Gold page | Cited pages |\n"
          "|---|---|:-:|---:|---:|---:|---:|:-:|---|")
        for r in cit:
            f = r["final"]
            gold = "–" if r["gold_hit"] is None else mark(r["gold_hit"])
            A(f"| {r['id']} | {r['category']} | {mark(r['ok'])} | {f['claims']} | {f['cited']} | "
              f"{f['pages_valid']}/{f['pages_total']} | {f['supported']}/{f['cited']} | {gold} | "
              f"{', '.join(map(str, f['cited_pages'])) or '–'} |")
        bad = [r for r in cit if not r["ok"]]
        if bad:
            A("\n### 5.3 Citation problems\n")
            for r in bad:
                A(f"- **{r['id']}** {cell(r['question'], 70)}: {'; '.join(r['problems'])}")
                for u in r["final"]["unsupported"][:2]:
                    A(f"  - unsupported: {u}")
                for u in r["final"]["uncited"][:2]:
                    A(f"  - uncited: {u}")

    # ---------------------------------------------------------------- 6
    A("\n## 6. Safety guards, robustness, API and persistence\n")
    for tier, title in (("guards", "6.1 Safety guards (unit tests)"), ("robustness", "6.2 Robustness"),
                        ("api", "6.3 HTTP API"), ("persistence", "6.4 Offline persistence")):
        rows = by_tier.get(tier, [])
        if not rows:
            continue
        A(f"### {title}: {sum(r['ok'] for r in rows)}/{len(rows)}\n")
        A("| ID | Check | Result | Detail |\n|---|---|:-:|---|")
        for r in rows:
            A(f"| {r['id']} | {cell(r['name'], 70)} | {mark(r['ok'])} | {cell(r['detail'], 80)} |")
        A("")

    # ---------------------------------------------------------------- 7
    A("\n## 7. Performance\n")
    rl = store.get("retrieval_latency", [])
    if rl:
        A(f"- Retrieval latency: median {statistics.median(rl) * 1000:.0f} ms, p95 {p95(rl) * 1000:.0f} ms, "
          f"max {max(rl) * 1000:.0f} ms ({len(rl)} questions)")
    if gen:
        A(f"- End-to-end answer latency: median {statistics.median(lat):.1f}s, p95 {p95(lat):.1f}s")
    A(f"- Peak memory of the evaluation process: {meta['rss']:.2f} GB")

    # ---------------------------------------------------------------- 8
    A("\n## 8. All failing checks\n")
    if not failed:
        A("None.")
    for c in failed:
        A(f"- **[{c['tier']}] {c['id']}** {cell(c['name'], 80)}: {cell(c['detail'], 160)}")

    findings = Path(__file__).resolve().parent / "FINDINGS.md"
    if findings.exists():
        A("\n## 9. Analysis and recommendations\n")
        A("> Written after reviewing the first full run; see `evaluation/FINDINGS.md`.\n")
        text = findings.read_text(encoding="utf-8").split("\n", 1)[1]
        A(text.replace("\n## ", "\n### ").replace("\n### Problems", "\n### Problems"))
    return "\n".join(L) + "\n"


def aggregate_citations(rows):
    out = {}
    for key in ("raw", "final"):
        claims = sum(r[key]["claims"] for r in rows)
        cited = sum(r[key]["cited"] for r in rows)
        sup = sum(r[key]["supported"] for r in rows)
        pt = sum(r[key]["pages_total"] for r in rows)
        pv = sum(r[key]["pages_valid"] for r in rows)
        out[key] = {"claims": claims,
                    "coverage": cited / claims if claims else 1.0,
                    "validity": pv / pt if pt else 1.0,
                    "precision": sup / cited if cited else 1.0}
    return out


def to_html(markdown_text, base_dir=None):
    """Render to a single self-contained HTML file (images embedded as data URIs)."""
    import base64
    import re
    from markdown_it import MarkdownIt
    body = MarkdownIt("commonmark", {"html": True}).enable("table").render(markdown_text)

    def embed(match):
        target = (Path(base_dir) / match.group(1)).resolve() if base_dir else None
        if target and target.exists():
            data = base64.b64encode(target.read_bytes()).decode()
            return f'src="data:image/png;base64,{data}" style="max-width:100%"'
        return match.group(0)

    body = re.sub(r'src="([^"]+\.png)"', embed, body)
    return f"<!doctype html><html><head><meta charset='utf-8'><title>Field Assistant Evaluation Report</title>" \
           f"<style>{CSS}</style></head><body>{body}</body></html>"


def to_pdf(html_path, pdf_path):
    if not Path(CHROME).exists():
        return False
    # Best effort only: skipped quietly if Chrome cannot print (open the HTML and
    # use the browser's Print > Save as PDF instead).
    import tempfile
    try:
        with tempfile.TemporaryDirectory() as profile:
            subprocess.run([CHROME, "--headless=new", "--disable-gpu", "--no-first-run",
                            f"--user-data-dir={profile}", "--no-pdf-header-footer",
                            f"--print-to-pdf={pdf_path}", f"file://{html_path}"],
                           capture_output=True, timeout=25)
    except Exception:  # noqa: BLE001
        return False
    return Path(pdf_path).exists()
